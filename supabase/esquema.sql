--  Cómo usarlo: en el panel de Supabase, abre "SQL Editor", pega todo
--  este archivo y presiona "Run". Se puede ejecutar más de una vez sin
--  romper nada (usa "if not exists" / "on conflict").
--
--  Contenido:
--    1. Configuración (dominio de correo permitido)
--    2. Tablas
--    3. Permisos (Row Level Security): solo usuarios con correo de la empresa
--    4. Almacenamiento de archivos adjuntos (bucket "adjuntos")
--    5. Tiempo real (para ver al instante los cambios de otros)
--    6. Funciones auxiliares
